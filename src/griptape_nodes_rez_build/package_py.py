"""Pieces of generated ``package.py`` files.

Every value placed in a generated file goes through ``repr()``, so a quote or a trailing
backslash in a name, description, or path cannot end a string early or change the code.
"""

from __future__ import annotations

# Key in ``platform_requires`` used on a platform that is not listed.
FALLBACK_PLATFORM_KEY = "*"

GENERATED_HEADER = "# -*- coding: utf-8 -*-\n# Generated by griptape-nodes-rez-build. Do not edit by hand.\n"


def list_literal(values: list[str]) -> str:
    """A list literal with one entry per line, as rez's own package files are written."""
    if not values:
        return "[]"
    entries = "".join(f"    {value!r},\n" for value in values)
    return f"[\n{entries}]"


def requires_block(requires: list[str], platform_requires: dict[str, list[str]] | None) -> str:
    """The ``requires`` of a package: a plain list, or one chosen per platform when rez resolves it.

    With *platform_requires*, the file carries a ``platform_requires`` dictionary keyed by
    ``<platform>-<arch>`` and a late-bound ``requires`` that picks this machine's entry, or the
    ``"*"`` entry on a platform that is not listed.
    """
    if platform_requires:
        entries = "".join(f"    {key!r}: {sorted(value)!r},\n" for key, value in sorted(platform_requires.items()))
        return f"""
# Dependencies differ by platform; rez picks this machine's list when it resolves.
platform_requires = {{
{entries}}}


@late()
def requires():
    key = system.platform + '-' + system.arch
    return this.platform_requires.get(key, this.platform_requires.get({FALLBACK_PLATFORM_KEY!r}, []))
"""
    if requires:
        return f"\nrequires = {list_literal(requires)}\n"
    return ""
